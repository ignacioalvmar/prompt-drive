/**
 * Generates the procedural vehicle meshes (OBJ) that ship in static/media/.
 * See vehicles-plan.md. Run with `npm run gen:vehicles` and commit the output.
 *
 * Frame (body OBJ, same as the Roadster's): +X forward, +Y up, +Z lateral,
 * origin on the ground under the rear axle. The engine rotates body OBJs by
 * -PI/2 on load, so +X becomes the vehicle's forward +Z.
 *
 * Materials are picked by the engine from the object name: the token after
 * the first "_" is looked up in its material palette (`_d`). Painted panels
 * use `map`, i.e. the Roadster's texture atlas (roadster-07b_map.jpg), with UVs
 * pointing at the atlas' white paint / black trim / glass / nose regions, so
 * new vehicles share the Roadster's look.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const mediaDir = path.join(root, 'static/media');

// --- Roadster atlas regions (1024x1024 px; v flipped for THREE's flipY) ----
function px(x0, y0, x1, y1) {
  return { u0: x0 / 1024, u1: x1 / 1024, v0: 1 - y1 / 1024, v1: 1 - y0 / 1024 };
}
const UV = {
  white: px(150, 880, 300, 980), // flat body paint
  black: px(8, 880, 44, 990), // trim / rubber
  glass: px(515, 55, 700, 320), // rear-screen panel (blue-grey gradient)
  sideGlass: px(95, 65, 225, 300), // side-window panel
  nose: px(370, 545, 865, 830), // Roadster front fascia: lamps + grille
  stripe: px(330, 1003, 780, 1016), // grey side stripe
};

// --- tiny OBJ writer ---------------------------------------------------------
class Obj {
  constructor(header) {
    this.lines = [`# ${header}`, '# Generated by scripts/gen-vehicles.js — do not edit by hand'];
    this.vi = 0;
    this.ti = 0;
    this.ni = 0;
    this.group = null;
  }
  object(name) {
    this.lines.push(`o ${name}`);
  }
  // Polygon (3 or 4 points) listed counter-clockwise as seen from the side it
  // should be visible from; `uv` maps corners bl, br, tr, tl of a rect.
  // `rot` rotates the texture a quarter turn (for portrait atlas panels).
  face(pts, uv = UV.white, { rot = false, normals = null } = {}) {
    const n = normals || [cross(sub(pts[1], pts[0]), sub(pts[pts.length - 1], pts[0]))];
    const corners = [
      [uv.u0, uv.v0],
      [uv.u1, uv.v0],
      [uv.u1, uv.v1],
      [uv.u0, uv.v1],
    ];
    const ref = [];
    pts.forEach((p, k) => {
      this.lines.push(`v ${f(p[0])} ${f(p[1])} ${f(p[2])}`);
      const c = corners[(k + (rot ? 1 : 0)) % 4];
      this.lines.push(`vt ${f(c[0])} ${f(c[1])}`);
      const nn = norm(normals ? normals[k] : n[0]);
      this.lines.push(`vn ${f(nn[0])} ${f(nn[1])} ${f(nn[2])}`);
      this.vi++;
      this.ti++;
      this.ni++;
      ref.push(`${this.vi}/${this.ti}/${this.ni}`);
    });
    this.lines.push(`f ${ref.join(' ')}`);
  }
  // Same polygon, visible from the other side.
  backFace(pts, uv, opts) {
    const r = [pts[1], pts[0], pts[3], pts[2]].slice(0, pts.length);
    this.face(pts.length === 4 ? r : [pts[0], pts[2], pts[1]], uv, opts);
  }
  // Axis-aligned box, outward faces. `skip` lists faces to omit:
  // px nx py ny pz nz.
  box(x0, x1, y0, y1, z0, z1, uv = UV.white, skip = []) {
    const F = {
      px: [[x1, y0, z1], [x1, y0, z0], [x1, y1, z0], [x1, y1, z1]],
      nx: [[x0, y0, z0], [x0, y0, z1], [x0, y1, z1], [x0, y1, z0]],
      pz: [[x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1]],
      nz: [[x1, y0, z0], [x0, y0, z0], [x0, y1, z0], [x1, y1, z0]],
      py: [[x0, y1, z0], [x0, y1, z1], [x1, y1, z1], [x1, y1, z0]],
      ny: [[x0, y0, z1], [x0, y0, z0], [x1, y0, z0], [x1, y0, z1]],
    };
    for (const k of Object.keys(F)) if (!skip.includes(k)) this.face(F[k], uv);
  }
  // Mirror helper: run fn for the +Z and -Z side (s = +1 / -1).
  both(fn) {
    fn(1);
    fn(-1);
  }
  write(file) {
    fs.writeFileSync(path.join(mediaDir, file), this.lines.join('\n') + '\n');
    console.log('Wrote', path.join('static/media', file));
  }
}

function f(n) {
  return (Math.round(n * 1e6) / 1e6).toString();
}
function sub(a, b) {
  return [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
}
function cross(a, b) {
  return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
}
function norm(a) {
  const l = Math.hypot(a[0], a[1], a[2]) || 1;
  return [a[0] / l, a[1] / l, a[2] / l];
}
// Side panel on the +Z (s=1) or -Z (s=-1) plane, given in (x, y) as seen from
// outside: bl, br, tr, tl for the +Z side. Mirrored ordering for -Z.
function sidePts(s, z, xy) {
  const pts = xy.map(([x, y]) => [x, y, s * z]);
  if (s > 0) return pts;
  // Seen from -Z, +X is on the viewer's left: reverse the winding.
  return pts.length === 4 ? [pts[1], pts[0], pts[3], pts[2]] : [pts[0], pts[2], pts[1]];
}

// =============================================================================
// Truck — cab-over 2-axle box truck. Wheelbase 4.2 m, track 2.0 m, r 0.5 m.
// =============================================================================
function truckBody() {
  const o = new Obj('Prompt Drive truck body');
  const CW = 1.2; // cab half-width
  const XB = 3.35; // cab back
  const XF = 5.35; // cab front (lower)
  const YF = 1.0; // cab floor
  const YB = 2.05; // belt line (window bottoms) = dash top
  const YT = 3.0; // windscreen top
  const YR = 3.2; // roof
  const XWIN = 4.25; // side window rear edge
  const YWT = 2.9; // side window top
  const rakeX = (y) => (y <= YB ? XF : XF - (0.2 * (y - YB)) / (YR - YB));
  const XWF = rakeX(YWT) - 0.12; // side window front edge
  const BW = 1.25; // box half-width
  const BX0 = -2.25;
  const BX1 = 3.25;
  const BY0 = 1.05;
  const BY1 = 3.6;

  // ---- shadow caster -------------------------------------------------------
  o.object('z_shadow_parts_shadow');
  o.box(BX0, XF + 0.15, 0.5, BY1, -BW, BW);

  // ---- painted exterior (atlas) ------------------------------------------
  o.object('z_map_body.001');
  // Cab lower front (white) + nose fascia from the Roadster atlas.
  o.face([[XF, YF, CW], [XF, YF, -CW], [XF, YB, -CW], [XF, YB, CW]], UV.white);
  o.face([[XF + 0.006, 1.3, 0.66], [XF + 0.006, 1.3, -0.66], [XF + 0.006, 1.94, -0.66], [XF + 0.006, 1.94, 0.66]], UV.nose);
  // Windscreen (raked) with white A-pillars.
  const WZ = 1.08;
  o.face([[XF, YB, WZ], [XF, YB, -WZ], [rakeX(YT), YT, -WZ], [rakeX(YT), YT, WZ]], UV.glass, { rot: true });
  o.both((s) => {
    const p = [[XF, YB, s * CW], [XF, YB, s * WZ], [rakeX(YT), YT, s * WZ], [rakeX(YT), YT, s * CW]];
    o.face(s > 0 ? p : [p[1], p[0], p[3], p[2]], UV.white);
  });
  // Header above the windscreen.
  o.face([[rakeX(YT), YT, CW], [rakeX(YT), YT, -CW], [rakeX(YR), YR, -CW], [rakeX(YR), YR, CW]], UV.white);
  // Roof and cab underside.
  o.box(XB, rakeX(YR), YR - 0.001, YR, -CW, CW, UV.white, ['px', 'nx', 'pz', 'nz', 'ny']);
  o.box(XB, XF, YF, YF + 0.001, -CW, CW, UV.black, ['px', 'nx', 'pz', 'nz', 'py']);
  // Cab back wall (mostly hidden by the box).
  o.face([[XB, YF, -CW], [XB, YF, CW], [XB, YR, CW], [XB, YR, -CW]], UV.white);
  // Cab sides: lower panel, rear panel, A-pillar, window top rail, glass.
  o.both((s) => {
    o.face(sidePts(s, CW, [[XB, YF], [XF, YF], [XF, YB], [XB, YB]]), UV.white);
    o.face(sidePts(s, CW, [[XB, YB], [XWIN, YB], [XWIN, YR], [XB, YR]]), UV.white);
    o.face(sidePts(s, CW, [[XWF, YB], [XF, YB], [rakeX(YWT), YWT], [XWF, YWT]]), UV.white);
    o.face(sidePts(s, CW, [[XWIN, YWT], [rakeX(YWT), YWT], [rakeX(YR), YR], [XWIN, YR]]), UV.white);
    o.face(sidePts(s, CW + 0.002, [[XWIN, YB], [XWF, YB], [XWF, YWT], [XWIN, YWT]]), UV.sideGlass, { rot: true });
    // Door seam + step.
    o.face(sidePts(s, CW + 0.003, [[XWIN - 0.03, 1.08], [XWIN, 1.08], [XWIN, YB], [XWIN - 0.03, YB]]), UV.black);
    o.box(4.75, 5.2, 0.72, 0.8, s > 0 ? CW - 0.25 : -CW, s > 0 ? CW : -CW + 0.25, UV.black);
  });
  // Roof air deflector (wedge from the roof up to the box top).
  const DZ = 1.12;
  const DX0 = XB + 0.05;
  const DX1 = 4.55;
  const DY = BY1 - 0.04;
  o.face([[DX1, YR, DZ], [DX1, YR, -DZ], [DX0, DY, -DZ], [DX0, DY, DZ]], UV.white);
  o.face([[DX0, YR, -DZ], [DX0, YR, DZ], [DX0, DY, DZ], [DX0, DY, -DZ]], UV.white);
  o.both((s) => o.face(sidePts(s, DZ, [[DX0, YR], [DX1, YR], [DX0, DY]]), UV.white));
  // Bumper, mirrors.
  o.box(XF - 0.1, XF + 0.15, 0.5, 0.98, -CW - 0.02, CW + 0.02, UV.black);
  o.both((s) => {
    o.box(4.95, 5.0, 2.32, 2.37, s > 0 ? CW : -CW - 0.22, s > 0 ? CW + 0.22 : -CW, UV.black);
    o.box(4.92, 5.0, 2.0, 2.62, s > 0 ? CW + 0.2 : -CW - 0.36, s > 0 ? CW + 0.36 : -CW - 0.2, UV.black);
  });
  // Cargo box: white with black base rail and rear door seams; grey stripe.
  o.box(BX0, BX1, BY0, BY1, -BW, BW, UV.white, ['ny']);
  o.box(BX0, BX1, BY0, BY0 + 0.001, -BW, BW, UV.black, ['px', 'nx', 'pz', 'nz', 'py']);
  o.both((s) => {
    o.face(sidePts(s, BW + 0.003, [[BX0, BY0], [BX1, BY0], [BX1, BY0 + 0.12], [BX0, BY0 + 0.12]]), UV.black);
    o.face(sidePts(s, BW + 0.003, [[BX0 + 0.1, 1.42], [BX1 - 0.1, 1.42], [BX1 - 0.1, 1.5], [BX0 + 0.1, 1.5]]), UV.stripe);
  });
  o.face([[BX0 - 0.003, BY0, -0.02], [BX0 - 0.003, BY0, 0.02], [BX0 - 0.003, BY1, 0.02], [BX0 - 0.003, BY1, -0.02]], UV.black);
  o.face([[BX0 - 0.003, BY1 - 0.08, -BW], [BX0 - 0.003, BY1 - 0.08, BW], [BX0 - 0.003, BY1, BW], [BX0 - 0.003, BY1, -BW]], UV.black);
  // Chassis: rails, fuel tanks, rear under-run bar, mud flaps.
  o.both((s) => {
    const z0 = s > 0 ? 0.4 : -0.6;
    o.box(BX0 + 0.1, XF - 0.1, 0.62, BY0, z0, z0 + 0.2, UV.black);
    const t0 = s > 0 ? 0.62 : -1.05;
    o.box(1.2, 2.5, 0.5, 0.98, t0, t0 + 0.43, UV.black);
    const m0 = s > 0 ? 0.78 : -1.22;
    o.box(-0.78, -0.75, 0.32, BY0, m0, m0 + 0.44, UV.black);
  });
  o.box(BX0 + 0.05, BX0 + 0.18, 0.42, 0.58, -1.12, 1.12, UV.black);

  // ---- lamps ---------------------------------------------------------------
  o.object('z_headlight_body.002');
  o.both((s) => o.box(XF, XF + 0.02, 1.2, 1.44, s > 0 ? 0.74 : -1.12, s > 0 ? 1.12 : -0.74, UV.white, ['nx']));
  o.object('z_rearlight_body.003');
  o.both((s) => o.box(BX0 - 0.02, BX0, 1.12, 1.34, s > 0 ? 0.86 : -1.16, s > 0 ? 1.16 : -0.86, UV.white, ['px']));
  o.object('z_redlight_body.004');
  o.both((s) => o.box(BX0 - 0.02, BX0, 1.12, 1.34, s > 0 ? 0.56 : -0.82, s > 0 ? 0.82 : -0.56, UV.white, ['px']));

  // ---- cabin interior (inward faces; the console anchors to this mesh) ----
  o.object('z_interior_Cube.008');
  const I = 0.01; // inset so interior and exterior skins never z-fight
  const ci = CW - I;
  // Floor, ceiling, back wall, lower front wall.
  o.face([[XB, YF + I, -ci], [XB, YF + I, ci], [XF, YF + I, ci], [XF, YF + I, -ci]]);
  o.face([[XB, YR - I, ci], [XB, YR - I, -ci], [rakeX(YR), YR - I, -ci], [rakeX(YR), YR - I, ci]]);
  o.backFace([[XB + I, YF, -ci], [XB + I, YF, ci], [XB + I, YR, ci], [XB + I, YR, -ci]]);
  o.backFace([[XF - I, YF, ci], [XF - I, YF, -ci], [XF - I, YB, -ci], [XF - I, YB, ci]]);
  o.both((s) => {
    const p = [[XF - I, YB, s * ci], [XF - I, YB, s * WZ], [rakeX(YT) - I, YT, s * WZ], [rakeX(YT) - I, YT, s * ci]];
    o.backFace(s > 0 ? p : [p[1], p[0], p[3], p[2]]);
  });
  o.backFace([[rakeX(YT) - I, YT, ci], [rakeX(YT) - I, YT, -ci], [rakeX(YR) - I, YR, -ci], [rakeX(YR) - I, YR, ci]]);
  o.both((s) => {
    o.backFace(sidePts(s, ci, [[XB, YF], [XF, YF], [XF, YB], [XB, YB]]));
    o.backFace(sidePts(s, ci, [[XB, YB], [XWIN, YB], [XWIN, YR], [XB, YR]]));
    o.backFace(sidePts(s, ci, [[XWF, YB], [XF, YB], [rakeX(YWT), YWT], [XWF, YWT]]));
    o.backFace(sidePts(s, ci, [[XWIN, YWT], [rakeX(YWT), YWT], [rakeX(YR), YR], [XWIN, YR]]));
  });
  // Dashboard: full-width shelf under the windscreen. Its top rear edge
  // (x 4.9, y 2.05) is the truck's `metrics.consoleMount`. Instrument pods on
  // both sides (the driver side is a setting) carry the binnacle, which the
  // engine places at metrics.steeringPos.
  o.box(4.9, XF - I, YF, YB, -ci, ci, UV.white, ['px', 'pz', 'nz']);
  o.both((s) => o.box(4.86, 5.12, YB, YB + 0.07, s > 0 ? 0.3 : -0.9, s > 0 ? 0.9 : -0.3, UV.white, ['px', 'ny']));

  // ---- seats -------------------------------------------------------------
  o.object('z_black_seats');
  o.both((s) => {
    const z = s * 0.6;
    o.box(3.95, 4.45, 1.0, 1.5, z - 0.27, z + 0.27, UV.black);
    o.box(3.62, 3.82, 1.5, 2.35, z - 0.27, z + 0.27, UV.black);
  });
  o.box(3.6, 4.3, 1.0, 1.35, -0.25, 0.25, UV.black); // engine tunnel / middle seat

  o.write('truck-01.obj');
}

// Truck wheel: tyre r 0.5, width 0.3, steel rim with lug holes so rotation
// reads. Axle along +Z from 0 (inboard) to 0.3 (outboard); the engine shifts
// it by -tyreWidth (0.15) so the tyre is centred on the track line.
function truckWheel() {
  const o = new Obj('Prompt Drive truck wheel');
  const N = 28;
  const R = 0.5;
  const RR = 0.31; // rim radius
  const W = 0.3;
  const ang = (k) => (k / N) * Math.PI * 2;
  const pt = (r, a, z) => [Math.cos(a) * r, Math.sin(a) * r, z];

  o.object('twheel_tire_tread');
  for (let k = 0; k < N; k++) {
    const a0 = ang(k);
    const a1 = ang(k + 1);
    const n0 = [Math.cos(a0), Math.sin(a0), 0];
    const n1 = [Math.cos(a1), Math.sin(a1), 0];
    o.face([pt(R, a0, 0), pt(R, a1, 0), pt(R, a1, W), pt(R, a0, W)], UV.black, { normals: [n0, n1, n1, n0] });
    // Sidewalls (annulus RR..R) on both faces.
    o.face([pt(RR, a0, W), pt(R, a0, W), pt(R, a1, W), pt(RR, a1, W)], UV.black);
    o.face([pt(RR, a1, 0), pt(R, a1, 0), pt(R, a0, 0), pt(RR, a0, 0)], UV.black);
    // Rim well (cylinder inside the tyre, facing the axle).
    o.face([pt(RR, a0, W), pt(RR, a1, W), pt(RR, a1, W - 0.05), pt(RR, a0, W - 0.05)], UV.black);
  }
  o.object('twheel_metal_rim');
  const ZR = W - 0.05;
  for (let k = 0; k < N; k++) {
    const a0 = ang(k);
    const a1 = ang(k + 1);
    o.face([[0, 0, ZR], pt(RR, a0, ZR), pt(RR, a1, ZR)], UV.white);
    o.face([[0, 0, 0.03], pt(RR, a1, 0.03), pt(RR, a0, 0.03)], UV.white);
  }
  o.object('twheel_black_hub');
  for (let k = 0; k < 6; k++) {
    // Six lug holes + a hub cap.
    const a = (k / 6) * Math.PI * 2;
    const c = pt(0.2, a, ZR + 0.004);
    const h = 0.035;
    o.face([[c[0] - h, c[1] - h, c[2]], [c[0] + h, c[1] - h, c[2]], [c[0] + h, c[1] + h, c[2]], [c[0] - h, c[1] + h, c[2]]], UV.black);
  }
  for (let k = 0; k < 8; k++) {
    const a0 = (k / 8) * Math.PI * 2;
    const a1 = ((k + 1) / 8) * Math.PI * 2;
    o.face([[0, 0, ZR + 0.02], pt(0.09, a0, ZR + 0.004), pt(0.09, a1, ZR + 0.004)], UV.black);
  }
  o.object('twheel_shadow_disc');
  for (let k = 0; k < 12; k++) {
    const a0 = (k / 12) * Math.PI * 2;
    const a1 = ((k + 1) / 12) * Math.PI * 2;
    o.face([[0, 0, W / 2], pt(R, a0, W / 2), pt(R, a1, W / 2)], UV.black);
  }
  o.write('truck_wheel-01.obj');
}

truckBody();
truckWheel();
